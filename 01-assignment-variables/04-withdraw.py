# 4.Update balance after withdrawal
 
balance = 12000
withdrawal = 3000

print(f"Current Balance is: {balance}")
print(f"Withdrawl Amount is: {withdrawal}")
print("="*40)
print()

updated_balance = balance - withdrawal

print(f"After Withdrawl the Current Balance is: {updated_balance}")

withdrawal_2 = 1500

update_balance_2 = updated_balance - withdrawal_2

print(f"withdrawl 2 Amount is :{withdrawal_2}")
print("="*40)
print(f"After second withdrawl the current balance is :{update_balance_2}")