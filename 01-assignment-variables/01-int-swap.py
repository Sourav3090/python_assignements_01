 # Q.1. Switch values of two integers

n1 = 20
n2 = 30

print(f"Before Swapping the Value of n1 is: {n1}")
print(f"Before Swapping the Value of n2 is: {n2}")

print("="*40) #to draw the line 10 times
print()
newvar = n1
n1 = n2
n2 = newvar

print(f"After Swapping the Value of n1 is: {n1}")
print(f"After Swapping the Value of n2 is: {n2}")
