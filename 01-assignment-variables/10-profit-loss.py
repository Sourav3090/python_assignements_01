# 10. Calculate profit or loss percentage
cost_price = 500
selling_price = 600

print(f"The Cost Price is: {cost_price}")
print(f"The Selling Price is: {selling_price}")
print()

profit = selling_price - cost_price
print(f"The profit is (Rs.): {profit}")
print()

percentage = (profit / cost_price) * 100

print(f"The Profit is (%): {percentage}")
